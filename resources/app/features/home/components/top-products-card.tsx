import Badge from '@/components/ui/badge';
import Flex from '@/components/ui/flex';
import Image from '@/components/ui/image';
import Skeleton from '@/components/ui/skeleton';
import {
  StackedItem,
  StackedItemContent,
  StackedItemMedia,
  StackedItems,
} from '@/components/ui/stacked-items';
import Text from '@/components/ui/text';
import { RouteConfig } from '@/config/route-config';
import OverviewCard from '@/features/home/components/overview-card';
import SkeletonLine from '@/features/home/components/skeleton-line';
import { getStockBadge } from '@/features/home/lib/stock';
import type { TopProduct } from '@/features/home/schemas/catalog/dashboard-overview';
import { ProductEmptyStateIcon } from '@/icons/empty-state';
import { theme } from '@/theme';
import { defineStyles, scoped } from '@/theme/mixins';
import { __, _n, sprintf } from '@/wpi18n';

const LOADING_ROW_COUNT = 5;
const BADGE_LINE_HEIGHT = '24px';
const LINE_HEIGHT = '22px';

type TopProductsCardProps = {
  products?: TopProduct[];
};

const NoProductState = () => {
  return (
    <Flex direction="column" align="center">
      <ProductEmptyStateIcon />
      <Text color="subdued" cssOverride={styles.empty}>
        {__('No sales yet', 'kirki-ecommerce')}
      </Text>
    </Flex>
  );
};

const TopProductsCard = ({ products }: TopProductsCardProps) => {
  return (
    <OverviewCard
      title={__('Top selling products', 'kirki-ecommerce')}
      info={__(
        'The five products with the most units sold in paid orders. All variants of a product are counted together.',
        'kirki-ecommerce',
      )}
      actionLabel={__('View all products', 'kirki-ecommerce')}
      actionTo={RouteConfig.Products.buildLink()}
    >
      {products === undefined ? (
        <div css={scoped(styles.body)}>
          <StackedItems>
            {Array.from({ length: LOADING_ROW_COUNT }, (_, index) => (
              <StackedItem key={index} id={String(index)} cssOverride={styles.item}>
                <StackedItemMedia>
                  <Skeleton width={PRODUCT_IMAGE_SIZE} height={PRODUCT_IMAGE_SIZE} />
                </StackedItemMedia>
                <StackedItemContent cssOverride={styles.details}>
                  <SkeletonLine width="60%" lineHeight={BADGE_LINE_HEIGHT} />
                  <SkeletonLine width="80%" lineHeight={LINE_HEIGHT} />
                </StackedItemContent>
              </StackedItem>
            ))}
          </StackedItems>
        </div>
      ) : products.length === 0 ? (
        <NoProductState />
      ) : (
        <div css={scoped(styles.body)}>
          <StackedItems>
            {products.map((product) => {
              const key = String(product.product_id ?? product.product_name);
              const stockBadge = getStockBadge(product);

              return (
                <StackedItem key={key} id={key} cssOverride={styles.item}>
                  <StackedItemMedia>
                    <Image
                      src={product.image}
                      alt={product.product_name ?? ''}
                      width={PRODUCT_IMAGE_SIZE}
                      height={PRODUCT_IMAGE_SIZE}
                      fit="cover"
                    />
                  </StackedItemMedia>
                  <StackedItemContent cssOverride={styles.details}>
                    <Flex align="center" gap={2} cssOverride={styles.titleRow}>
                      <Text variant="paragraph" weight="medium" color="primary" truncate>
                        {product.product_name}
                      </Text>
                      {stockBadge && (
                        <Badge variant={stockBadge.variant} cssOverride={styles.badge}>
                          {stockBadge.text}
                        </Badge>
                      )}
                    </Flex>
                    <Flex align="center" gap={2} cssOverride={styles.meta}>
                      <Text variant="small" color="secondary" cssOverride={styles.nowrap}>
                        {sprintf(
                          /* translators: %s: revenue generated by the product, with currency */
                          __('%s generated', 'kirki-ecommerce'),
                          product.base_revenue_money_object.display,
                        )}
                      </Text>
                      <span css={scoped(styles.dot)} aria-hidden="true" />
                      <Text variant="small" color="secondary" cssOverride={styles.nowrap}>
                        {sprintf(
                          /* translators: %d: number of units sold */
                          _n(
                            '%d unit sold',
                            '%d units sold',
                            product.units_sold,
                            'kirki-ecommerce',
                          ),
                          product.units_sold,
                        )}
                      </Text>
                    </Flex>
                  </StackedItemContent>
                </StackedItem>
              );
            })}
          </StackedItems>
        </div>
      )}
    </OverviewCard>
  );
};

TopProductsCard.displayName = 'TopProductsCard';

export default TopProductsCard;

const PRODUCT_IMAGE_SIZE = '48px';

const styles = defineStyles({
  body: {
    padding: `0 ${theme.spacing[3]} ${theme.spacing[6]} ${theme.spacing[3]}`,
  },
  item: {
    height: 'auto',
    flexWrap: 'nowrap',
    gap: theme.spacing[3],
    padding: `${theme.spacing[3]} ${theme.spacing[4]}`,
  },
  details: {
    flex: 1,
    minWidth: 0,
    gap: theme.spacing[1],
  },
  titleRow: {
    minWidth: 0,
  },
  badge: {
    flexShrink: 0,
  },
  meta: {
    minWidth: 0,
    flexWrap: 'wrap',
    rowGap: 0,
  },
  dot: {
    width: '4px',
    height: '4px',
    flexShrink: 0,
    borderRadius: theme.radius.full,
    backgroundColor: theme.colors.text.disabled,
  },
  nowrap: {
    whiteSpace: 'nowrap',
  },
  empty: {
    flex: 1,
    display: 'flex',
    alignItems: 'center',
    justifyContent: 'center',
    padding: theme.spacing[6],
    textAlign: 'center',
  },
});
